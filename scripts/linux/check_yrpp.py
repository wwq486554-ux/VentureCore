#!/usr/bin/env python3
"""Verify that external/YRpp is the pinned YRpp revision and that its content
matches the tracked sha256 manifest.

``external/YRpp`` is an external build dependency (YRpp carries no license
declaration and is not vendored), so the pin has to answer two questions:

1. *which revision* is installed - ``src/Core/EnginePin.h`` (``VC_YRPP_PIN``)
   must be the **full 40-hex commit id** of ``external/YRpp`` (a git checkout's
   HEAD or the ``external/YRpp.commit`` stamp written by
   ``scripts/linux/fetch_yrpp.sh`` for a non-git copy).  Prefixes are only used
   for display (``VC_YRPP_PIN_SHORT``); a short commit id is never accepted,
   because a prefix matches several real commits and a truncated stamp hides a
   changed tree.  A git checkout must also be **clean** - uncommitted or
   untracked files mean the content is not the commit.
2. *which content* is installed - the sha256 of every file below
   ``external/YRpp`` must match ``external/YRpp.sha256``, and the file set must
   be identical (no missing/extra file).  The manifest is tracked in the
   repository and generated by ``fetch_yrpp.sh --write-manifest`` from the
   accepted tree, so a local re-fetch cannot silently install different content
   under the same claimed commit (the gap in a non-git "trust me" copy).

This script is the build-time gate: ``scripts/linux/build_linux.sh`` calls it
before compiling and aborts when the local YRpp checkout does not match the pin.
``src/Engine/EngineCompat.h`` is the second (compile-time) gate; together they
make sure a build that happens to compile is also a build against the engine
headers the platform was written for.

The revision is taken from, in order:

1. the YRpp git checkout itself (``external/YRpp/.git`` exists, e.g. once it is
   a real submodule);
2. ``external/YRpp.commit`` (written by ``scripts/linux/fetch_yrpp.sh`` for
   local, non-git copies).

Usage:
    scripts/linux/check_yrpp.py [--quiet]
    scripts/linux/check_yrpp.py --write-manifest
        Regenerate ``external/YRpp.sha256`` from the installed tree, after the
        revision checks passed.  Only do this for an accepted pin/content
        update - the manifest is the content pin other machines verify against.
    scripts/linux/check_yrpp.py --verify-tree PATH
        Content-only check: compare the tree at PATH against the tracked
        manifest (``fetch_yrpp.sh`` uses it on the staged copy *before* it
        replaces the installed tree).  The revision is not checked here.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
YRPP_DIR = REPO_ROOT / "external" / "YRpp"
PIN_HEADER = REPO_ROOT / "src" / "Core" / "EnginePin.h"
COMMIT_FILE = REPO_ROOT / "external" / "YRpp.commit"
MANIFEST = REPO_ROOT / "external" / "YRpp.sha256"
MANIFEST_NAME = "external/YRpp.sha256"

PIN_ANY_RE = re.compile(r'#define\s+VC_YRPP_PIN\s+"([0-9a-fA-F]+)"')
PIN_SHORT_RE = re.compile(r'#define\s+VC_YRPP_PIN_SHORT\s+"([0-9a-fA-F]+)"')
FULL_COMMIT_RE = re.compile(r"^[0-9a-f]{40}$")
MANIFEST_LINE_RE = re.compile(r"^([0-9a-f]{64})  (.+)$")


def fail(message: str) -> int:
    print(f"check_yrpp: FAIL - {message}", file=sys.stderr)
    return 1


def read_expected_pin() -> str:
    """Return the full 40-hex pin; abort when the header does not define one."""
    if not PIN_HEADER.is_file():
        raise SystemExit(f"check_yrpp: missing {PIN_HEADER}")

    text = PIN_HEADER.read_text(encoding="utf-8", errors="replace")
    match = PIN_ANY_RE.search(text)
    if not match:
        raise SystemExit(
            "check_yrpp: FAIL - VC_YRPP_PIN is not defined in src/Core/EnginePin.h"
        )

    pin = match.group(1).lower()
    if not FULL_COMMIT_RE.fullmatch(pin):
        raise SystemExit(
            "check_yrpp: FAIL - VC_YRPP_PIN must be the full 40-hex commit id\n"
            f"            got: '{pin}' ({len(pin)} hex digit(s))\n"
            "            A short id matches several revisions; shorten only\n"
            "            VC_YRPP_PIN_SHORT (display) - never VC_YRPP_PIN."
        )

    # VC_YRPP_PIN_SHORT is display-only: require it to be the prefix of the pin
    # so the log line and the version resource cannot drift from the real pin.
    short_match = PIN_SHORT_RE.search(text)
    if short_match and short_match.group(1).lower() != pin[:8]:
        raise SystemExit(
            "check_yrpp: FAIL - VC_YRPP_PIN_SHORT is display-only but does not match the pin\n"
            f"            VC_YRPP_PIN       = {pin}\n"
            f"            VC_YRPP_PIN_SHORT = {short_match.group(1).lower()} (expected {pin[:8]})"
        )

    return pin


def git_state(path: Path) -> tuple[str | None, list[str], str | None]:
    """Return (HEAD, dirty entries, error) for a git work tree."""
    if not (path / ".git").exists():
        return None, [], None

    try:
        head = subprocess.run(
            ["git", "-C", str(path), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=30,
        )
        status = subprocess.run(
            ["git", "-C", str(path), "status", "--porcelain", "--untracked-files=normal"],
            capture_output=True,
            text=True,
            timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        return None, [], f"cannot run git: {exc}"

    if head.returncode != 0:
        return None, [], "git rev-parse HEAD failed (broken or incomplete .git)"
    if status.returncode != 0:
        return None, [], "git status failed (broken or incomplete .git)"

    commit = head.stdout.strip().lower() or None
    dirty = [line for line in status.stdout.splitlines() if line.strip()]
    return commit, dirty, None


def read_commit_file() -> str | None:
    if not COMMIT_FILE.is_file():
        return None
    value = COMMIT_FILE.read_text(encoding="utf-8", errors="replace").strip().lower()
    return value or None


def tree_entries(tree: Path) -> tuple[dict[str, str], list[str]]:
    """Hash every regular file below `tree` (git metadata excluded)."""
    root = tree.resolve()
    entries: dict[str, str] = {}
    problems: list[str] = []

    for current, dirs, files in os.walk(root):
        dirs[:] = sorted(name for name in dirs if name != ".git")
        for name in files:
            # A `.git` *file* (submodule gitlink) is git metadata, not content.
            if name == ".git":
                continue
            path = Path(current) / name
            rel = path.relative_to(root).as_posix()
            if "\n" in rel:
                problems.append(f"{rel!r}: the file name contains a newline")
                continue
            if path.is_symlink():
                problems.append(f"{rel}: symlink (the manifest covers regular files only)")
                continue
            try:
                entries[rel] = hashlib.sha256(path.read_bytes()).hexdigest()
            except OSError as exc:
                problems.append(f"{rel}: cannot be read ({exc})")

    return entries, problems


def manifest_text(entries: dict[str, str]) -> str:
    """Deterministic manifest text: '<sha256>  <path>' sorted by path."""
    return "".join(f"{entries[rel]}  {rel}\n" for rel in sorted(entries))


def _manifest_path_problem(rel: str) -> str | None:
    if rel.startswith("/") or re.match(r"^[A-Za-z]:", rel):
        return "absolute path"
    if "\\" in rel:
        return "backslash separator (the manifest uses '/')"
    if rel.startswith("./"):
        return "leading './'"
    if any(part in ("", ".", "..") for part in rel.split("/")):
        return "empty, '.' or '..' path element"
    return None


def read_manifest() -> tuple[dict[str, str] | None, list[str]]:
    """Return ({path: sha256}, problems); entries is None when missing/unreadable."""
    if not MANIFEST.is_file():
        return None, [f"{MANIFEST_NAME} is missing"]

    try:
        text = MANIFEST.read_text(encoding="utf-8", errors="strict")
    except (OSError, UnicodeDecodeError) as exc:
        return None, [f"{MANIFEST_NAME} cannot be read: {exc}"]

    entries: dict[str, str] = {}
    problems: list[str] = []
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip():
            continue
        match = MANIFEST_LINE_RE.match(line)
        if not match:
            problems.append(f"line {number}: expected '<64-hex sha256>  <relative path>'")
            continue
        digest, rel = match.group(1), match.group(2)
        path_problem = _manifest_path_problem(rel)
        if path_problem:
            problems.append(f"line {number}: {path_problem}: {rel!r}")
            continue
        if rel in entries:
            problems.append(f"line {number}: duplicate path: {rel}")
            continue
        entries[rel] = digest

    return entries, problems


def write_manifest(entries: dict[str, str]) -> None:
    """Write the manifest atomically (same-directory rename)."""
    text = manifest_text(entries)
    temporary = MANIFEST.with_name(f".{MANIFEST.name}.new.{os.getpid()}")
    try:
        with open(temporary, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.replace(temporary, MANIFEST)
    finally:
        try:
            temporary.unlink()
        except OSError:
            pass


def compare_tree(tree: Path, expected: dict[str, str]) -> tuple[bool, list[str]]:
    """Compare a tree against the manifest; returns (ok, summary lines)."""
    current, problems = tree_entries(tree)
    lines: list[str] = list(problems)

    changed = sorted(rel for rel in expected if rel in current and expected[rel] != current[rel])
    missing = sorted(rel for rel in expected if rel not in current)
    unexpected = sorted(rel for rel in current if rel not in expected)

    for rel in changed:
        lines.append(f"changed: {rel} (manifest {expected[rel][:12]}... found {current[rel][:12]}...)")
    for rel in missing:
        lines.append(f"missing: {rel}")
    for rel in unexpected:
        lines.append(f"unexpected: {rel}")

    count = len(changed) + len(missing) + len(unexpected) + len(problems)
    if count == 0:
        return True, [f"{len(expected)} file(s) match {MANIFEST_NAME}"]

    lines.insert(
        0,
        f"content mismatch: {len(changed)} changed, {len(missing)} missing, "
        f"{len(unexpected)} unexpected file(s); {len(expected)} file(s) in the manifest",
    )
    return False, lines


def print_failure(header: str, lines: list[str], limit: int = 12) -> int:
    print(f"check_yrpp: FAIL - {header}", file=sys.stderr)
    for line in lines[:limit]:
        print(f"            {line}", file=sys.stderr)
    if len(lines) > limit:
        print(f"            ... and {len(lines) - limit} more", file=sys.stderr)
    return 1


def revision_of_installed_tree() -> tuple[str | None, list[str]]:
    """Return (commit, problems) for external/YRpp (git HEAD or the stamp file)."""
    commit, dirty, error = git_state(YRPP_DIR)
    if (YRPP_DIR / ".git").exists():
        if error:
            return None, [f"external/YRpp is a git checkout but {error}"]
        if commit is None:
            return None, ["external/YRpp is a git checkout but its HEAD cannot be determined"]
        if dirty:
            preview = "; ".join(dirty[:5])
            if len(dirty) > 5:
                preview += f"; ... ({len(dirty)} entries)"
            return None, [
                "external/YRpp is a dirty git checkout (uncommitted or untracked changes),",
                f"so its content is not commit {commit}:",
                f"  {preview}",
                "Commit/stash/clean it (a submodule update should leave it pristine).",
            ]
        return commit, []

    stamp = read_commit_file()
    if stamp is None:
        return None, [
            "cannot determine the YRpp revision (no git checkout and no",
            f"{COMMIT_FILE.name}). Run scripts/linux/fetch_yrpp.sh.",
        ]
    if not FULL_COMMIT_RE.fullmatch(stamp):
        return None, [
            f"external/{COMMIT_FILE.name} must hold the full 40-hex commit id,",
            f"but it holds '{stamp}' ({len(stamp)} hex digit(s));",
            "a short stamp is not accepted - re-run scripts/linux/fetch_yrpp.sh.",
        ]
    return stamp, []


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Check the pinned YRpp revision and its sha256 content manifest."
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--write-manifest",
        action="store_true",
        help="regenerate external/YRpp.sha256 from the installed tree (after the revision checks)",
    )
    mode.add_argument(
        "--verify-tree",
        metavar="PATH",
        help="content-only check of PATH against the tracked manifest",
    )
    parser.add_argument("--quiet", action="store_true", help="only report problems")
    args = parser.parse_args()

    # --verify-tree: content only, no revision checks (used on a staged copy).
    if args.verify_tree is not None:
        tree = Path(args.verify_tree)
        if not tree.is_dir():
            return fail(f"--verify-tree: '{args.verify_tree}' is not a directory")
        expected, problems = read_manifest()
        if expected is None:
            return fail(problems[0] if problems else f"{MANIFEST_NAME} is missing")
        if problems:
            return print_failure(f"{MANIFEST_NAME} is not a valid manifest", problems)
        ok, lines = compare_tree(tree, expected)
        if not ok:
            return print_failure(f"the tree at '{args.verify_tree}' does not match {MANIFEST_NAME}", lines)
        if not args.quiet:
            print(f"check_yrpp: OK - '{args.verify_tree}' matches {MANIFEST_NAME} ({len(expected)} file(s))")
        return 0

    pin = read_expected_pin()

    if not (YRPP_DIR / "YRPP.h").is_file():
        return fail(
            "external/YRpp is missing or incomplete.\n"
            "            fetch it with: scripts/linux/fetch_yrpp.sh"
        )

    commit, problems = revision_of_installed_tree()
    if problems:
        return print_failure(problems[0], problems[1:])
    if commit != pin:
        return print_failure(
            "YRpp revision mismatch (only the full commit id is accepted; prefixes never match)",
            [
                f"expected (VC_YRPP_PIN): {pin}",
                f"actual:                 {commit}",
                "fetch the pinned revision with: scripts/linux/fetch_yrpp.sh --from PATH",
                "or update the pin in src/Core/EnginePin.h (with a compatibility review)",
                "and re-run the content-manifest review.",
            ],
        )

    if args.write_manifest:
        entries, problems = tree_entries(YRPP_DIR)
        if problems:
            return print_failure("cannot generate the content manifest", problems)
        write_manifest(entries)
        if not args.quiet:
            print(f"check_yrpp: wrote {MANIFEST_NAME} ({len(entries)} file(s))")

    expected, problems = read_manifest()
    if expected is None:
        return print_failure(
            f"{MANIFEST_NAME} is missing - the pinned content cannot be verified",
            [
                "Regenerate it after a deliberate pin/content review with:",
                "  scripts/linux/fetch_yrpp.sh --write-manifest",
            ],
        )
    if problems:
        return print_failure(f"{MANIFEST_NAME} is not a valid manifest", problems)

    ok, lines = compare_tree(YRPP_DIR, expected)
    if not ok:
        return print_failure(f"the installed YRpp tree does not match {MANIFEST_NAME}", lines)

    if not args.quiet:
        print(f"check_yrpp: OK - YRpp {pin} ({len(expected)} file(s) match {MANIFEST_NAME})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
