#pragma once

// ---------------------------------------------------------------------------
// Platform version metadata, shared by the C++ code and src/version.rc.
//
// Bump these when publishing. Keep VC_PRERELEASE_SUFFIX defined for experimental
// builds and comment it out for a stable release.
// ---------------------------------------------------------------------------

#include "EnginePin.h"

#define VC_VERSION_MAJOR    0
#define VC_VERSION_MINOR    4
#define VC_VERSION_REVISION 0
#define VC_VERSION_PATCH    0
#define VC_PRERELEASE_SUFFIX "experimental"

#define VC_STR_INNER(x) #x
#define VC_STR(x) VC_STR_INNER(x)
#define VC_VERSION_LONG_STR \
	VC_STR(VC_VERSION_MAJOR) "." VC_STR(VC_VERSION_MINOR) "." \
	VC_STR(VC_VERSION_REVISION) "." VC_STR(VC_VERSION_PATCH)

#ifdef VC_PRERELEASE_SUFFIX
#define VC_VERSION_DISPLAY "v" VC_VERSION_LONG_STR "-" VC_PRERELEASE_SUFFIX
#else
#define VC_VERSION_DISPLAY "v" VC_VERSION_LONG_STR
#endif

// Comma-separated form for the VERSIONINFO resource.
#define VC_FILEVERSION \
	VC_VERSION_MAJOR, VC_VERSION_MINOR, VC_VERSION_REVISION, VC_VERSION_PATCH

#ifdef RELEASE
#define VC_BUILD_TYPE "RELEASE"
#elif defined(NIGHTLY)
#define VC_BUILD_TYPE "NIGHTLY"
#else
#define VC_BUILD_TYPE "LOCAL"
#endif

// Git metadata is generated at build time into $(IntDir)/Generated by the build
// script (Linux) or the ComputeGitInfo target in VentureCore.props (MSBuild).
#include "VentureCore.Git.h"

#ifdef STR_GIT_COMMIT
#define VC_GIT_COMMIT STR_GIT_COMMIT
#else
#define VC_GIT_COMMIT "unknown"
#endif

#ifdef STR_GIT_REF
#define VC_GIT_REF STR_GIT_REF
#else
#define VC_GIT_REF "unknown"
#endif

#ifdef STR_GIT_DIRTY
#define VC_GIT_DIRTY STR_GIT_DIRTY
#else
#define VC_GIT_DIRTY ""
#endif
